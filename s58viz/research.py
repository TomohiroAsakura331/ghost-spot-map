    st.write("人口・道路などを調整すると、森林4〜6割の区画（森林と市街地の境目）で寄与が高く、ほとんど森林がない区画と森林ばかりの区画では低くなります。単純集計で森林0〜5%の区画に掲載が多いこととは区別します。「森林が多いほど高い」とは解釈できません。")
