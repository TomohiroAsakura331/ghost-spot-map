    st.write("首都圏1都7県において、都県別ランキング上位30%の心霊スポットが掲載されている区画と環境要因との関連を調べます。心霊現象の存在や発生を検証する研究ではなく、ウェブサイトの掲載と環境の関連を分析する研究です。体験談（STEP 6）は使用していません。")
    st.subheader("採用方法：都県ごとに上位30%、合計679件")
    st.write("全国心霊マップの標準の「ランキング」を2026-10-30に取得。1都7県の掲載総数は2,252件です。各都県について ceil（掲載総数×0.30）件を一覧の順位で上から採用しました。「注目度」の並び順は使っていません。")
